"""Streamlit views for the churn analytics application."""

import json
from pathlib import Path

import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
import streamlit as st

from src.data_loader import (
    CATEGORICAL_COLUMNS,
    FEATURE_COLUMNS,
    NUMERIC_COLUMNS,
    TARGET,
    default_data_path,
    load_dataset,
)
from src.eda import SEGMENT_COLUMNS, churn_rate_by, churn_summary, numeric_correlations
from src.explainability import local_feature_effects
from src.predict import load_model_bundle, predict_customers

MODEL_PATH = Path("models/churn_pipeline.joblib")
METRICS_PATH = Path("models/metrics.json")


@st.cache_data(show_spinner=False)
def _load_data(path: str) -> pd.DataFrame:
    return load_dataset(path)


def _dataset_or_message() -> pd.DataFrame | None:
    path = default_data_path()
    try:
        return _load_data(str(path))
    except FileNotFoundError as exc:
        st.info(f"{exc}\n\nDataset setup: see [data/README.md](data/README.md).")
    except ValueError as exc:
        st.error(f"The configured dataset could not be validated: {exc}")
    return None


def _model_or_message():
    try:
        return load_model_bundle(MODEL_PATH)
    except (FileNotFoundError, ValueError) as exc:
        st.warning(str(exc))
    return None


def _chart(fig, height: int = 360) -> None:
    fig.update_layout(
        height=height,
        margin=dict(l=12, r=12, t=48, b=12),
        paper_bgcolor="rgba(0,0,0,0)",
        plot_bgcolor="rgba(0,0,0,0)",
    )
    st.plotly_chart(fig, use_container_width=True)


def _page_overview(frame: pd.DataFrame | None) -> None:
    st.title("Customer churn | Executive overview")
    st.caption("A practical view of observed churn patterns and validated model outputs.")
    if frame is None:
        st.info(
            "Add a valid IBM Telco-style CSV to begin. No customer data or metrics are "
            "generated by this application."
        )
        return
    summary = churn_summary(frame)
    columns = st.columns(4)
    columns[0].metric("Customers", f"{summary['customers']:,}")
    columns[1].metric("Churned", f"{summary['churned']:,}")
    columns[2].metric("Churn rate", f"{summary['churn_rate']:.1%}")
    columns[3].metric("Retained", f"{summary['retained']:,}")
    left, right = st.columns(2)
    with left:
        fig = px.pie(
            frame,
            names=TARGET,
            hole=0.58,
            title="Observed customer status",
            color=TARGET,
            color_discrete_map={"Yes": "#fb7185", "No": "#38bdf8"},
        )
        _chart(fig)
    with right:
        rates = churn_rate_by(frame, "Contract Length")
        fig = px.bar(
            rates,
            x="Contract Length",
            y="churn_rate",
            color="churn_rate",
            color_continuous_scale="Teal",
            title="Observed churn rate by contract",
            labels={"churn_rate": "Churn rate", "Contract Length": "Contract length"},
        )
        fig.update_yaxes(tickformat=".0%")
        _chart(fig)
    tenure = churn_rate_by(frame, "Tenure")
    fig = px.bar(
        tenure,
        x="Tenure",
        y="churn_rate",
        title="Observed churn rate by tenure band",
        labels={"tenure": "Tenure (months)", "churn_rate": "Churn rate"},
    )
    fig.update_yaxes(tickformat=".0%")
    _chart(fig)
    st.caption(
        f"Data quality check: {summary['duplicates']:,} exact duplicate row(s). "
        "Segment patterns are associations, not evidence that a feature causes churn."
    )


def _page_analytics(frame: pd.DataFrame | None) -> None:
    st.title("Exploratory analytics")
    if frame is None:
        return
    st.caption("Filter the observed dataset. Segment churn rates are descriptive, not causal.")
    filter_columns = ["Contract Length", "Subscription Type", "Gender"]
    selections = {}
    for column in filter_columns:
        options = sorted(frame[column].dropna().astype(str).unique())
        selections[column] = st.multiselect(
            column, options, default=options, key=f"filter_{column}"
        )
    observed_tenure = frame["Tenure"].dropna()
    if observed_tenure.empty:
        st.warning("Tenure is entirely missing; no tenure filter can be applied.")
        filtered = frame.copy()
    else:
        minimum_tenure = int(observed_tenure.min())
        maximum_tenure = int(observed_tenure.max())
        low, high = st.slider(
            "Tenure range (months)",
            min_value=minimum_tenure,
            max_value=maximum_tenure,
            value=(minimum_tenure, maximum_tenure),
        )
        filtered = frame.loc[frame["Tenure"].between(low, high)]
    for column, selected in selections.items():
        filtered = filtered.loc[filtered[column].astype(str).isin(selected)]
    if filtered.empty:
        st.warning("No customers match these filters.")
        return
    rates_columns = st.columns(3)
    for index, column in enumerate(["Contract Length", "Subscription Type", "Gender"]):
        rates = churn_rate_by(filtered, column)
        fig = px.bar(
            rates,
            x=column,
            y="churn_rate",
            title=f"Churn by {column}",
            labels={"churn_rate": "Churn rate"},
            color="churn_rate",
            color_continuous_scale="Teal",
        )
        fig.update_yaxes(tickformat=".0%")
        with rates_columns[index]:
            _chart(fig, height=330)
    left, right = st.columns(2)
    with left:
        fig = px.histogram(
            filtered,
            x="Total Spend",
            color=TARGET,
            barmode="overlay",
            opacity=0.72,
            title="Monthly charges by observed outcome",
        )
        _chart(fig)
    with right:
        correlation = numeric_correlations(filtered)
        fig = px.imshow(
            correlation,
            text_auto=".2f",
            color_continuous_scale="RdBu",
            zmin=-1,
            zmax=1,
            title="Numeric feature correlations",
        )
        _chart(fig)
    st.subheader("Segment comparison")
    st.dataframe(
        filtered.groupby(["Contract Length", "Subscription Type"], dropna=False)
        .agg(
            customers=(TARGET, "size"),
            churn_rate=(TARGET, lambda values: values.eq(1).mean()),
            mean_total_spend=("Total Spend", "mean"),
        )
        .reset_index()
        .sort_values("churn_rate", ascending=False),
        use_container_width=True,
        hide_index=True,
    )


def _page_performance(frame: pd.DataFrame | None) -> None:
    st.title("Model performance")
    if not METRICS_PATH.is_file():
        st.info("No trained metrics are available. Configure data and run `python -m src.train`.")
        return
    try:
        metrics = json.loads(METRICS_PATH.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        st.error(f"Could not read model metrics at {METRICS_PATH}: {exc}")
        return
    cv_rows = []
    for model_name, scores in metrics["cv_results"].items():
        cv_rows.append(
            {
                "Model": model_name,
                **{
                    f"{metric} (mean)": values["mean"]
                    for metric, values in scores.items()
                },
                **{
                    f"{metric} (std)": values["std"]
                    for metric, values in scores.items()
                },
            }
        )
    st.subheader("Training-only cross-validation")
    test_rows = []
    for model_name, scores in metrics.get("test_results", {}).items():
        test_rows.append(
            {
                "Model": model_name,
                **{
                    f"{metric} (test)": scores[metric]
                    for metric in ["precision", "recall", "f1", "roc_auc"]
                },
            }
        )
    cv_table = pd.DataFrame(cv_rows)
    test_table = pd.DataFrame(test_rows)
    if not test_table.empty:
        cv_table = cv_table.merge(test_table, on="Model", how="left")
    st.dataframe(cv_table, use_container_width=True, hide_index=True)
    st.caption(
        f"Selected by {metrics['selection_metric']}. "
        f"Model: {metrics['selected_model']}."
    )
    test = metrics["test_metrics"]
    st.subheader(f"Untouched test set ({test['test_rows']:,} rows)")
    st.caption(f"Evaluation source: {metrics.get('test_source', 'recorded test set')}.")
    cv_auc = metrics["cv_results"][metrics["selected_model"]]["roc_auc"]["mean"]
    auc_gap = cv_auc - test["roc_auc"]
    if auc_gap >= 0.10:
        st.warning(
            f"Generalization warning: selected-model CV ROC-AUC "
            f"({cv_auc:.3f}) exceeds supplied test ROC-AUC ({test['roc_auc']:.3f}) "
            f"by {auc_gap:.3f}. Investigate dataset construction and distribution "
            "differences before relying on these predictions."
        )
    score_columns = st.columns(4)
    for column, metric in zip(score_columns, ["precision", "recall", "f1", "roc_auc"]):
        column.metric(metric.replace("_", " ").title(), f"{test[metric]:.3f}")
    matrix = test["confusion_matrix"]
    fig = px.imshow(
        matrix,
        text_auto=True,
        x=["Predicted retained", "Predicted churn"],
        y=["Actual retained", "Actual churn"],
        color_continuous_scale="Blues",
        title=f"Confusion matrix at threshold {test['threshold']:.2f}",
    )
    _chart(fig, height=330)
    st.info(
        "The threshold is the documented 0.50 baseline, not tuned on the test set. "
        "Higher recall can catch more likely churners but may also flag more retained "
        "customers (lower precision); choose an operating point using validation data "
        "and business costs, never this final test set."
    )
    curve = test.get("roc_curve")
    if curve:
        fig = go.Figure()
        fig.add_trace(
            go.Scatter(
                x=curve["false_positive_rate"],
                y=curve["true_positive_rate"],
                mode="lines",
                name=f"{metrics['selected_model']} (AUC {test['roc_auc']:.3f})",
            )
        )
        fig.add_trace(
            go.Scatter(x=[0, 1], y=[0, 1], mode="lines", name="Chance", line={"dash": "dash"})
        )
        fig.update_layout(
            title="ROC curve on untouched test set",
            xaxis_title="False positive rate",
            yaxis_title="True positive rate",
        )
        _chart(fig)
    if metrics.get("global_permutation_importance"):
        st.subheader("Global permutation importance")
        st.caption(
            "Feature shuffling measures model reliance on the untouched test set; "
            "it does not establish cause."
        )
        _chart(
            px.bar(
                pd.DataFrame(metrics["global_permutation_importance"])
                .head(12)
                .sort_values("importance"),
                x="importance",
                y="feature",
                orientation="h",
                title="Change in test-set ROC-AUC after feature permutation",
            )
        )
    if metrics.get("tree_feature_importance"):
        st.subheader(
            f"Tree feature importance: {metrics['tree_importance_model']}"
        )
        st.caption(
            "The classifier's impurity-based importance reflects model structure and "
            "feature association; it is not causal evidence."
        )
        _chart(
            px.bar(
                pd.DataFrame(metrics["tree_feature_importance"])
                .head(12)
                .sort_values("importance"),
                x="importance",
                y="feature",
                orientation="h",
                title="Tree-based feature importance",
            )
        )


def _page_prediction(frame: pd.DataFrame | None) -> None:
    st.title("Customer churn prediction")
    bundle = _model_or_message()
    if bundle is None:
        return
    st.warning("Predictions are estimates, not certainties. Model associations are not causal.")
    threshold = st.slider(
        "High-risk probability threshold",
        min_value=0.10,
        max_value=0.90,
        value=float(bundle["threshold"]),
        step=0.05,
        help="This changes the displayed risk category only; it does not retrain the model.",
    )
    if st.session_state.get("customer_prediction") is None:
        st.session_state["customer_prediction"] = None
    with st.form("customer_prediction_form"):
        st.subheader("Customer attributes")
        inputs = {}
        columns = st.columns(3)
        for index, column in enumerate(FEATURE_COLUMNS):
            with columns[index % 3]:
                if column in CATEGORICAL_COLUMNS:
                    options = (
                        sorted(frame[column].dropna().astype(str).unique())
                        if frame is not None
                        else ["Unknown"]
                    )
                    inputs[column] = st.selectbox(column, options, key=f"input_{column}")
                elif column in NUMERIC_COLUMNS:
                    observed = (
                        frame[column].dropna()
                        if frame is not None
                        else pd.Series(dtype=float)
                    )
                    maximum = float(observed.max()) if not observed.empty else 1000.0
                    default = float(observed.median()) if not observed.empty else 0.0
                    inputs[column] = st.number_input(
                        column,
                        min_value=0.0,
                        max_value=max(1.0, maximum * 1.5),
                        value=min(default, max(1.0, maximum * 1.5)),
                        step=1.0,
                    )
                else:
                    raise ValueError(f"No prediction input widget is configured for '{column}'.")
        submitted = st.form_submit_button("Estimate churn risk", type="primary")
    if submitted:
        record = pd.DataFrame([inputs], columns=FEATURE_COLUMNS)
        result = predict_customers(record, bundle["pipeline"], threshold)
        st.session_state["customer_prediction"] = result
    result = st.session_state.get("customer_prediction")
    if result is not None:
        probability = float(result["churn_probability"].iloc[0])
        category = "High" if probability >= threshold else "Low"
        st.metric("Estimated churn probability", f"{probability:.1%}")
        st.metric("Displayed risk category", category)
        if bundle.get("reference_profile") is not None:
            effects = local_feature_effects(
                bundle["pipeline"], result.loc[:, FEATURE_COLUMNS], bundle["reference_profile"]
            )
            st.subheader("Largest model response changes")
            st.caption(
                "Each value compares this record with a reference profile after changing "
                "one feature at a time; it is a model sensitivity view, not a causal explanation."
            )
            _chart(
                px.bar(
                    effects.head(8).sort_values("probability_change"),
                    x="probability_change",
                    y="feature",
                    orientation="h",
                    title="Probability change versus reference profile",
                )
            )

    st.divider()
    st.subheader("Optional batch CSV scoring")
    uploaded = st.file_uploader("Upload customer records (no Churn target column)", type=["csv"])
    if uploaded is not None:
        try:
            batch = pd.read_csv(uploaded)
            scored = predict_customers(batch, bundle["pipeline"], threshold)
        except (
            pd.errors.ParserError,
            pd.errors.EmptyDataError,
            UnicodeDecodeError,
            ValueError,
        ) as exc:
            st.error(f"Upload could not be scored: {exc}")
        else:
            st.success(f"Scored {len(scored):,} customer record(s).")
            st.dataframe(scored.head(100), use_container_width=True)
            st.download_button(
                "Download scored CSV",
                data=scored.to_csv(index=False).encode("utf-8"),
                file_name="churn_scored.csv",
                mime="text/csv",
            )


def _page_retention(frame: pd.DataFrame | None) -> None:
    st.title("Retention insights")
    if frame is None:
        return
    overall_rate = frame[TARGET].eq(1).mean()
    st.caption(
        "These suggestions describe observed associations. They do not prove that an "
        "intervention will prevent churn."
    )
    segment_tables = {column: churn_rate_by(frame, column) for column in SEGMENT_COLUMNS}
    minimum = max(10, int(len(frame) * 0.01))
    findings = []
    for column, summary in segment_tables.items():
        for _, row in summary.iterrows():
            if row["customers"] >= minimum and row["churn_rate"] > overall_rate:
                findings.append(
                    {
                        "segment": f"{column}: {row[column]}",
                        "customers": int(row["customers"]),
                        "observed churn rate": float(row["churn_rate"]),
                        "difference vs overall": float(row["churn_rate"] - overall_rate),
                    }
                )
    if findings:
        evidence = pd.DataFrame(findings).sort_values(
            "observed churn rate", ascending=False
        ).head(10)
        st.subheader("Higher-churn observed segments")
        st.dataframe(
            evidence.style.format(
                {
                    "observed churn rate": "{:.1%}",
                    "difference vs overall": "{:+.1%}",
                }
            ),
            use_container_width=True,
            hide_index=True,
        )
        st.markdown(
            "- Review onboarding and early-tenure support for segments with elevated "
            "observed churn.\n"
            "- Validate service, billing, and contract concerns with customer feedback "
            "before choosing an intervention.\n"
            "- Pilot any change with a controlled experiment; segment associations alone "
            "cannot show that an action will reduce churn."
        )
    else:
        st.info(
            f"No segment with at least {minimum} customers exceeded the overall "
            "observed churn rate in the selected dataset."
        )

    st.subheader("Optional hypothetical financial scenario")
    st.caption(
        "All inputs below are assumptions supplied by you; the result is not an observed "
        "saving, forecast, or evidence that the intervention works."
    )
    left, right, third = st.columns(3)
    customers = left.number_input("Customers to contact", min_value=0, value=0, step=10)
    effectiveness = right.number_input(
        "Assumed incremental retention (%)", min_value=0.0, max_value=100.0, value=0.0
    )
    value = third.number_input(
        "Assumed value per retained customer", min_value=0.0, value=0.0, step=10.0
    )
    cost = st.number_input("Assumed cost per contacted customer", min_value=0.0, value=0.0)
    if customers and effectiveness and value:
        retained = customers * effectiveness / 100
        gross = retained * value
        net = gross - customers * cost
        st.metric("Hypothetical net impact", f"{net:,.2f}")
        st.caption(
            f"Based on assumptions: {retained:,.1f} incremental retained customers, "
            f"{gross:,.2f} gross value, and {customers * cost:,.2f} contact cost."
        )


def render_dashboard() -> None:
    st.sidebar.title("Churn intelligence")
    st.sidebar.caption("Observed customer patterns and validated estimates")
    page = st.sidebar.radio(
        "Navigate",
        [
            "Executive overview",
            "Exploratory analytics",
            "Model performance",
            "Customer prediction",
            "Retention insights",
        ],
        label_visibility="collapsed",
    )
    frame = _dataset_or_message()
    if page == "Executive overview":
        _page_overview(frame)
    elif page == "Exploratory analytics":
        _page_analytics(frame)
    elif page == "Model performance":
        _page_performance(frame)
    elif page == "Customer prediction":
        _page_prediction(frame)
    else:
        _page_retention(frame)
